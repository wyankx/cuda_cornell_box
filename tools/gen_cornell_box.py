#!/usr/bin/env python3
"""Deterministic Cornell box scene generator for test task 02.

Geometry is the classic Cornell box measurement data (Program of Computer
Graphics, Cornell University), units are millimetres. Differences from the
original data:
  * every quad is split into 2 triangles (the original quads are slightly
    non-planar, as in the source data);
  * the light is lowered 0.5 mm below the ceiling (y = 548.3 instead of 548.8)
    so that light and ceiling triangles are not coplanar: otherwise the
    closest hit between them is ambiguous;
  * normals are explicit (vn), pointing into the room for walls and outwards
    for blocks; vertex order matches the normal (CCW when looking against
    the normal).

Usage:
    python3 -I tools/gen_cornell_box.py            # writes to ../scene
    python3 -I tools/gen_cornell_box.py --out DIR
"""
