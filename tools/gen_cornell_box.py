def sub(a, b):
    return tuple(a[i] - b[i] for i in range(3))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return sum(a[i] * b[i] for i in range(3))


def normalize(a):
    l = dot(a, a) ** 0.5
    return tuple(x / l for x in a)


def centroid(points):
    n = len(points)
    return tuple(sum(p[i] for p in points) / n for i in range(3))


def oriented_quad(name, quad, block_center):
    """Return (vertices in CCW order around the normal, normal)."""
    n = normalize(cross(sub(quad[1], quad[0]), sub(quad[2], quad[0])))
    c = centroid(quad)
    if name == "light":
        want = (0.0, -1.0, 0.0)                     # the light emits downwards
    elif block_center is not None:
        want = sub(c, block_center)                 # blocks: normal points outwards
    else:
        want = sub(ROOM_CENTER, c)                  # walls: normal points into the room
    if dot(n, want) < 0:
        quad = list(reversed(quad))
        n = tuple(-x for x in n)
    return quad, n


def build_obj():
    lines = [
        "# Cornell box for BHS test task 02 (Quake RTX on Apple Metal)",
        "# Units: millimetres. Right-handed, Y up. Camera: see scene.json.",
        "# Generated by tools/gen_cornell_box.py — do not edit by hand.",
        "# Light is lowered to y=%.1f (0.5 mm below the ceiling) to avoid coplanar triangles." % LIGHT_Y,
        "mtllib cornell_box.mtl",
    ]
    v_count = 0
    n_count = 0
    body = []
    for name, mtl, quads in QUADS:
        block_center = None
        if name.endswith("block"):
            block_center = centroid([p for q in quads for p in q])
        body.append("")
        body.append("o %s" % name)
        body.append("usemtl %s" % mtl)
        for quad in quads:
            q, n = oriented_quad(name, quad, block_center)
            for p in q:
                body.append("v %.1f %.1f %.1f" % p)
            body.append("vn %.6f %.6f %.6f" % n)
            n_count += 1
            b = v_count + 1
            body.append("f %d//%d %d//%d %d//%d" % (b, n_count, b + 1, n_count, b + 2, n_count))
            body.append("f %d//%d %d//%d %d//%d" % (b, n_count, b + 2, n_count, b + 3, n_count))
            v_count += 4
    return "\n".join(lines + body) + "\n", v_count


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(here, "..", "scene"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    obj, nverts = build_obj()
    with open(os.path.join(args.out, "cornell_box.obj"), "w", newline="\n") as f:
        f.write(obj)
    with open(os.path.join(args.out, "cornell_box.mtl"), "w", newline="\n") as f:
        f.write(MTL)
    print("written %d vertices, %d triangles to %s" % (nverts, nverts // 2, os.path.normpath(args.out)))


if __name__ == "__main__":
    main()
